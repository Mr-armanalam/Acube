// Thumbnail helpers (utils/thumbnail.ts): image validation, frame
// extraction failure modes, data-URL conversion, and the
// file > URL > frame > auto precedence rule.
import { describe, it, expect } from "vitest";
import {
  MAX_THUMBNAIL_BYTES,
  SUGGESTED_FRAME_INDEX,
  THUMBNAIL_FRAME_FRACTIONS,
  dataUrlToFile,
  describeThumbnailChoice,
  extractVideoFrames,
  resolveThumbnailChoice,
  validateImageFile,
} from "../utils/thumbnail";

function imageFile(name: string, size: number, type: string): File {
  return new File([new ArrayBuffer(size)], name, { type });
}

describe("validateImageFile", () => {
  it("accepts JPEG and PNG under the limit", () => {
    expect(validateImageFile(imageFile("a.jpg", 1024, "image/jpeg"))).toBeNull();
    expect(validateImageFile(imageFile("a.png", 1024, "image/png"))).toBeNull();
  });

  it("accepts a file exactly at the 5 MB limit", () => {
    expect(
      validateImageFile(imageFile("a.jpg", MAX_THUMBNAIL_BYTES, "image/jpeg")),
    ).toBeNull();
  });

  it("rejects a file over 5 MB", () => {
    expect(
      validateImageFile(imageFile("a.jpg", MAX_THUMBNAIL_BYTES + 1, "image/jpeg")),
    ).toBe("Image must be 5 MB or smaller.");
  });

  it("rejects a non-image MIME type", () => {
    expect(validateImageFile(imageFile("a.gif", 1024, "image/gif"))).toBe(
      "Choose a JPG or PNG image.",
    );
    expect(validateImageFile(imageFile("a.mp4", 1024, "video/mp4"))).toBe(
      "Choose a JPG or PNG image.",
    );
  });

  it("falls back to the extension when the browser left the type blank", () => {
    expect(validateImageFile(imageFile("a.JPG", 1024, ""))).toBeNull();
    expect(validateImageFile(imageFile("a.txt", 1024, ""))).toBe(
      "Choose a JPG or PNG image.",
    );
  });
});

describe("resolveThumbnailChoice precedence", () => {
  const frames = ["data:frame0", "data:frame1", "data:frame2"];
  const file = imageFile("thumb.png", 100, "image/png");

  it("a file wins over a URL and a selected frame", () => {
    const choice = resolveThumbnailChoice({
      file,
      url: "https://example.com/thumb.jpg",
      frameDataUrls: frames,
      selectedFrameIndex: 2,
    });
    expect(choice).toEqual({ kind: "file", file });
  });

  it("a URL wins over a selected frame", () => {
    const choice = resolveThumbnailChoice({
      file: null,
      url: "https://example.com/thumb.jpg",
      frameDataUrls: frames,
      selectedFrameIndex: 0,
    });
    expect(choice).toEqual({
      kind: "url",
      url: "https://example.com/thumb.jpg",
    });
  });

  it("a selected frame wins over nothing", () => {
    expect(
      resolveThumbnailChoice({
        file: null,
        url: "  ",
        frameDataUrls: frames,
        selectedFrameIndex: 1,
      }),
    ).toEqual({ kind: "frame", frameIndex: 1, dataUrl: "data:frame1" });
  });

  it("nothing chosen is auto (server-generated)", () => {
    expect(
      resolveThumbnailChoice({
        file: null,
        url: "",
        frameDataUrls: frames,
        selectedFrameIndex: null,
      }),
    ).toEqual({ kind: "auto" });
  });

  it("an out-of-range frame index falls through to auto", () => {
    expect(
      resolveThumbnailChoice({
        file: null,
        url: "",
        frameDataUrls: frames,
        selectedFrameIndex: 7,
      }),
    ).toEqual({ kind: "auto" });
  });

  it("describes each choice for the review step", () => {
    expect(describeThumbnailChoice({ kind: "file", file })).toBe(
      "Image file: thumb.png",
    );
    expect(
      describeThumbnailChoice({ kind: "url", url: "https://example.com/t.jpg" }),
    ).toBe("https://example.com/t.jpg");
    expect(
      describeThumbnailChoice({
        kind: "frame",
        frameIndex: 1,
        dataUrl: "data:frame1",
      }),
    ).toBe("Auto-generated frame 2 of 3");
    expect(describeThumbnailChoice({ kind: "auto" })).toBe(
      "Auto-generated by the server",
    );
  });
});

describe("thumbnail frame sampling", () => {
  it("samples 5% / 50% / 90% with the middle frame suggested", () => {
    expect(THUMBNAIL_FRAME_FRACTIONS).toEqual([0.05, 0.5, 0.9]);
    expect(SUGGESTED_FRAME_INDEX).toBe(1);
  });
});

describe("dataUrlToFile", () => {
  it("converts a JPEG data URL to a File", () => {
    // "aGVsbG8=" is base64 for "hello".
    const file = dataUrlToFile("data:image/jpeg;base64,aGVsbG8=", "thumbnail.jpg");
    expect(file).not.toBeNull();
    expect(file?.name).toBe("thumbnail.jpg");
    expect(file?.type).toBe("image/jpeg");
    expect(file?.size).toBe(5);
  });

  it("returns null for a non-image data URL", () => {
    expect(dataUrlToFile("not-a-data-url", "thumbnail.jpg")).toBeNull();
  });
});

describe("extractVideoFrames", () => {
  it("rejects — never resolves fake frames — when the video cannot be read", async () => {
    const file = new File([new ArrayBuffer(1024)], "demo.mp4", {
      type: "video/mp4",
    });
    // jsdom has no URL.createObjectURL and no media decoding; the
    // helper must reject rather than hang or invent frames.
    try {
      await extractVideoFrames(file, undefined, 50);
      expect.unreachable("should have rejected");
    } catch (err: unknown) {
      expect(err).toBeInstanceOf(Error);
      expect((err as Error).message).toBe("Could not read frames from this video.");
    }
  });
});
